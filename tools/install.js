/* The Bleep Test files to install on the watch, as metadata.json lists them,
   and the Espruino code that writes them to Storage.

   Used by the test harness (tests/harness.js) and by `npm run bundle`,
   which writes dist/bleeptest-install.js: paste that into the Espruino Web
   IDE and send it to the watch to install without the App Loader.

   node tools/install.js [out file]   (default dist/bleeptest-install.js) */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

/* [{name, content, evaluate}] for every storage entry in metadata.json.
   Throws on non-ASCII source (Espruino strings are bytes). */
function appFiles(root) {
  root = root || ROOT;
  const meta = JSON.parse(fs.readFileSync(path.join(root, "metadata.json")));
  return meta.storage.map(s => {
    const content = fs.readFileSync(path.join(root, s.url), "utf8");
    if (/[^\x00-\x7f]/.test(content)) throw new Error(`${s.url} has non-ASCII characters`);
    return { name: s.name, content, evaluate: !!s.evaluate };
  });
}

/* Code that writes `content` to Storage file `name`, in chunks so the
   console line buffer never gets too long. */
function writeFileCmds(name, content) {
  const CHUNK = 512;
  if (!content.length) return `require("Storage").write(${JSON.stringify(name)},"");\n`;
  let out = "";
  for (let i = 0; i < content.length; i += CHUNK) {
    const part = JSON.stringify(content.substr(i, CHUNK));
    out += i == 0
      ? `require("Storage").write(${JSON.stringify(name)},${part},0,${content.length});\n`
      : `require("Storage").write(${JSON.stringify(name)},${part},${i});\n`;
  }
  return out;
}

/* Code that installs one file: evaluated files (the icon) are written as
   the value of their expression, like the App Loader does. */
function fileCmds(f) {
  return f.evaluate
    ? `require("Storage").write(${JSON.stringify(f.name)},${f.content.trim()});\n`
    : writeFileCmds(f.name, f.content);
}

/* Code that writes every file plus the App Loader's record of the app
   (<id>.info, so the launcher lists it), one statement per line. */
function installCode(root) {
  root = root || ROOT;
  const meta = JSON.parse(fs.readFileSync(path.join(root, "metadata.json")));
  const files = appFiles(root);
  // the same <id>.info the App Loader writes (core/js/appinfo.js), which
  // the launcher lists apps from
  const infoName = meta.id + ".info";
  const info = { id: meta.id, name: meta.shortName || meta.name };
  if (meta.type && meta.type != "app") info.type = meta.type;
  if (files.some(f => f.name == meta.id + ".app.js")) info.src = meta.id + ".app.js";
  if (files.some(f => f.name == meta.id + ".img")) info.icon = meta.id + ".img";
  info.version = meta.version;
  if (meta.tags) info.tags = meta.tags;
  info.files = [infoName].concat(files.map(f => f.name)).join(",");
  if (meta.data) info.data = meta.data.map(d => d.name || d.wildcard).join(",");
  let out = "";
  for (const f of files) out += fileCmds(f);
  out += `require("Storage").writeJSON(${JSON.stringify(infoName)},${JSON.stringify(info)});\n`;
  return out;
}

/* A Web IDE installer: installCode(), then a reload so the boot code is
   rebuilt. */
function bundle(root) {
  root = root || ROOT;
  const meta = JSON.parse(fs.readFileSync(path.join(root, "metadata.json")));
  let out = `// Bleep Test ${meta.version} installer for the Espruino Web IDE.\n` +
    `// Connect to the watch, paste this into the editor (right-hand side) and\n` +
    `// press "Send to Espruino". Generated by tools/install.js: don't edit.\n`;
  out += installCode(root);
  out += `print("Bleep Test ${meta.version} installed");\nsetTimeout(load, 500);\n`;
  return out;
}

module.exports = { appFiles, writeFileCmds, fileCmds, installCode, bundle };

if (require.main === module) {
  const out = path.resolve(process.argv[2] || path.join(ROOT, "dist/bleeptest-install.js"));
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, bundle());
  console.log(`Wrote ${path.relative(process.cwd(), out)} (${fs.statSync(out).size} bytes)`);
}
